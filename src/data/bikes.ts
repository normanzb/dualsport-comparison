export type Bike = Named & {
  slug: string;
};

/** Everything a bike is written with. The slug is derived from the first three. */
type Named = {
  make: string;
  model: string;
  year?: string;
  spec: {
    serviceInterval: string;
    dryWeight: string;
    wetWeight: string;
    tank: string;
    gears: string;
    seatHeight: string;
    /** Published ground clearance; "n/a" where the maker has not released one. */
    clearance: string;
    engine: string;
    /** Claimed crank figures, not dyno. */
    power: string;
    torque: string;
    price: string;
  };
  /** Numeric mirrors of the table, for sorting and bar scales. */
  n: {
    wetKg: number;
    dryKg: number;
    tankL: number;
    seatMm: number;
    priceFrom: number;
    /** Service interval normalised to miles; null when quoted in engine hours. */
    serviceMi: number | null;
    /** null where no figure is published */
    clearanceMm: number | null;
    cc: number;
    hp: number;
    nm: number;
  };
  condition: "new" | "used";
  /**
   * Which side the final drive runs down. Left on every chain-driven bike here;
   * the shaft-drive HP2 runs its drive down the right. "none" is for a bike with
   * no one-sided drive to point at.
   */
  driveSide?: "left" | "right" | "none";
  /**
   * Which side the silencer sits on. Right on most of these, but the LC4
   * 690/701, the HP2 and the WR125R route it down the left, so the right-hand
   * view of those shows no exhaust at all. "none" where it is not one-sided.
   */
  exhaustSide?: "left" | "right" | "none";
  /** Brand colour, contrast-checked against the graphite ground. */
  ink: string;
  /** Secondary brand colour, used for the section's minor accents. */
  inkAlt: string;
  /** The verdict: what the numbers in the table add up to. */
  note: string;
  /** Mechanical or historical background specific to this bike. */
  story?: string;
  /**
   * Background shared by every bike on the same platform, written once and
   * referenced, because six LC4s repeating the same paragraph would drift apart.
   */
  platform?: readonly string[];
};

